    private void btnTambah4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambah4ActionPerformed
        // TODO add your handling code here:
        String NamaGuru, NIPguru, Mapel, JenisKelamin;
        NamaGuru = nama_guru.getText();
        NIPguru = NIP.getText();
        Mapel = "";
        if(rbRPL1.isSelected()==true){
            Mapel = "RPL";
        }
        else if(rbTKJ1.isSelected()){
            Mapel = "TKJ";
        }
        else if(rbANM1.isSelected()){
            Mapel = "ANM";
        }
        else if(rbKLN1.isSelected()){
            Mapel = "KLN";
        }
        else{
            Mapel = "PHT";
        }
        JenisKelamin = "";
        if(Laki.isSelected()){
            JenisKelamin = "Laki-Laki";
        }
        else{
            JenisKelamin = "Perempuan";
        }

        modelGuru.addRow(new Object[]{NamaGuru, NIPguru, Mapel, JenisKelamin});
        tblGuru.setModel(modelGuru);
    }//GEN-LAST:event_btnTambah4ActionPerformed

